/* ============================================================
 * config/breed.js · 繁育参数（M12 / M16）
 *
 * 设计来源：宝可梦 / 洛克王国的「母定种 + 按槽部分继承 + 道具锁规则」。
 * 本作的落地版本：
 *   · 子代鱼种 = 雌鱼鱼种（母方定种，不存在退化形态）
 *   · 子代性别 = 50/50，与父母无关
 *   · 词条按槽独立继承：母 40% / 父 40% / 全新 20%
 *   · 继承后等级会涨/跌：+1 25%（同种 33%，再加「亲缘」）、−1 8%
 *   · L5 只能靠繁育得到（自然掉落最高 L4）
 *
 * 成本必须按「雌方稀有度」定价：
 *   SSR 雌 + R 雄 → SSR 鱼苗，若只收 30 金币鱼饵，
 *   就是 970–1,300 倍的印钞机（实测）。所以 SSR 收 2.5 万。
 *
 * M16 流程改动（去掉培育缸）：
 *   产卵 → 鱼卵直接进仓库「鱼卵」子页（可以囤着，不占栏位）
 *        → 在仓库点「孵化」才占一个培育栏位
 *        → 到点后鱼苗直接进鱼篓
 * 好处是「配一次种」和「开一次孵化」被拆成两步，
 * 玩家可以先攒几颗蛋，再一口气挑好蛋孵，不用守着计时。
 * ============================================================ */

